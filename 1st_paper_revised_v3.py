import numpy as np
import torch
from scipy.linalg import sqrtm, logm

def von_neumann_entropy(rho):
    eigvals = np.linalg.eigvals(rho)
    eigvals = np.real(eigvals[eigvals > 1e-12])
    return -np.sum(eigvals * np.log(eigvals))

def quantum_relative_entropy(rho, sigma):
    # S(rho || sigma) = Tr(rho log rho - rho log sigma)
    eig_rho = np.linalg.eigvals(rho)
    eig_rho = np.real(eig_rho[eig_rho > 1e-12])

    # 数值稳定性处理
    val = np.real(np.trace(rho @ logm(rho) -
                          rho @ logm(sigma)))
    return max(0, val)

