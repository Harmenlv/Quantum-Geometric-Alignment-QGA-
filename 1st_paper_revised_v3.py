def compute_quantum_fidelity(rho1, rho2):
    """计算两个密度矩阵之间的量子保真度"""
    # F(rho1, rho2) = [tr(sqrt(sqrt(rho1)rho2(sqrt(rho1))))]^2
    sqrt_rho1 = sqrtm(rho1)
    matrix_inner = sqrt_rho1 @ rho2 @ sqrt_rho1
    sqrt_inner = sqrtm(matrix_inner)
    fidelity = np.real(np.trace(sqrt_inner))**2
    return np.clip(fidelity, 0, 1)

def get_choi_matrix_refined(model_op, input_data):
    """
    真正的功能对齐：通过输入数据的响应构造密度矩阵
    这才能真正实现‘坐标无关’ (Coordinate-Free)
    """
    with torch.no_grad():
        features = model_op(input_data) # [Batch, Channels, ...]
        features = features.view(features.size(0), features.size(1), -1)
        features = features.mean(dim=2) # 空间池化

        # 构造协方差矩阵作为密度矩阵 rho
        # 这捕捉的是通道间的相关性，无论通道如何置换，其特征空间的统计特性(特征值谱)是不变的
        rho = torch.cov(features.T)
        rho = rho / torch.trace(rho)
        return rho.detach().numpy()

