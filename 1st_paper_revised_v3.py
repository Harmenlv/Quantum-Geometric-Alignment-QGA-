def quantum_fidelity(rho1, rho2):
    # 数学性能优化：处理可能的数值精度问题
    mat = sqrtm(rho1) @ rho2 @ sqrtm(rho1)
    # 矩阵开方并取迹的平方
    f = np.real(np.trace(sqrtm(mat)))**2
    return np.clip(f, 0, 1)

def get_refined_density_matrix(weight, input_sample):
    """
    通过引入输入流形响应，构造真正的功能态密度矩阵
    """
    # 模拟算子输出: y = Wx
    out = torch.matmul(input_sample, weight.T)
    # 计算输出特征的协方差作为算子的‘本质态’
    cov = torch.cov(out.T)
    rho = cov / torch.trace(cov)
    return rho.detach().numpy()

