def compute_spectral_distance(rho1, rho2):
    """计算两个算子态之间的谱距离"""
    spec1 = np.sort(np.real(np.linalg.eigvals(rho1)))[::-1]
    spec2 = np.sort(np.real(np.linalg.eigvals(rho2)))[::-1]

    # 确保维度对齐（针对宽窄模型对齐）
    max_dim = max(len(spec1), len(spec2))
    s1 = np.pad(spec1, (0, max_dim - len(spec1)))
    s2 = np.pad(spec2, (0, max_dim - len(spec2)))

    return np.linalg.norm(s1 - s2)

